export type GamesI18nKey = keyof typeof messages.RU;

/** Возвращает локализованную строку игр с простой подстановкой параметров. */
export function gameT(key: GamesI18nKey, params: Record<string, string | number> = {}): string {
  const language = getLanguageMode();
  const dictionary = messages[language] ?? messages.RU;
  const template = String(dictionary[key] ?? messages.RU[key] ?? key);
  return Object.entries(params).reduce(
    (result, [name, value]) => result.split(`{${name}}`).join(String(value)),
    template,
  );
}
